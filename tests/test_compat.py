class ProtocolTests(unittest.TestCase):
    def setUp(self):
        self.codec = Codec(b"test-signing-key", b"0123456789abcdef")

    def test_independent_dotnet_fixture(self):
        # Generated by tools/protocol_reference using System.Security.Cryptography.
        form = b"bbmPacket=Kpc87sZQP8ZxVhrhSfwqeau6OVCX91rq3%2BaRtuhedYClM3tK0%2FKEZH%2Br1jVeYKKLHiBavgdxcKmMzk7TNIT1P4lIIgqZVhIUnuMnGUHlUbxTSNeeubDNBhHmDwhqzNL4kxyhzJPx4xAUiBKPYCNyfw1Zz%2BI6iSnDOv%2FlEyb5ny3%2BV9taqqWpsqS0Eg9i2KQhL9ghlUXU3OMy7%2F%2B3rEl8ejdyIuBhqSTFkc2cJ%2BoWPtQ%3D"
        packet, wire = self.codec.decode(form, "application/x-www-form-urlencoded")
        self.assertEqual(packet, {"userId": 7, "sessionId": 11, "txId": 3})
        self.assertEqual(wire, "bbmPacket")

    def test_plain_bootstrap_form(self):
        packet, wire = self.codec.decode(b"jsonPacket=%7B%7D", "application/x-www-form-urlencoded; charset=UTF-8")
        self.assertEqual((packet, wire), ({}, "jsonPacket"))

    def test_signature_required(self):
        other = Codec(b"wrong-signing-key", b"0123456789abcdef")
        with self.assertRaises(ProtocolError):
            self.codec.decode(other.encode({"userId": 1}), "application/x-www-form-urlencoded")

    def test_expired_packet_rejected(self):
        with self.assertRaises(ProtocolError):
            self.codec.decode(self.codec.encode({}, expires=time.time()-3600), "application/x-www-form-urlencoded")

    def test_malformed_forms_rejected(self):
        for body in (b"jsonPacket=[]", b"jsonPacket={}&jsonPacket={}", b"bbmPacket=broken", b"jsonPacket={}&bbmPacket=x", b"jsonPacket=null"):
            with self.subTest(body=body), self.assertRaises(ProtocolError):
                self.codec.decode(body, "application/x-www-form-urlencoded")

    def test_redaction(self):
        self.assertEqual(redact({"nested": {"sessionId": 99, "accessToken": "secret"}, "txId": 3}),
                         {"nested": {"sessionId": "<redacted>", "accessToken": "<redacted>"}, "txId": 3})


class StateTests(unittest.TestCase):
    def test_persistence_bad_token_and_session_rotation(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp)/"state.db"
            first = State(path)
            account = first.create()
            second = State(path)
            self.assertTrue(second.exists(account["udid"]))
            self.assertIsNone(second.login(account["udid"], "wrong"))
            session1 = second.login(account["udid"], account["accessToken"])
            self.assertTrue(first.valid_session(session1["userId"], session1["sessionId"]))
            session2 = first.login(account["udid"], account["accessToken"])
            self.assertFalse(second.valid_session(session1["userId"], session1["sessionId"]))
            self.assertTrue(second.valid_session(session2["userId"], session2["sessionId"]))
            self.assertFalse(second.valid_session(session2["userId"], 2**70))

    def test_dev_login_and_persisted_wallet(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp)/"state.db"
            state = State(path, {"coin": 500, "candy": 500})
            session1 = state.login_dev("local-device")
            self.assertEqual(state.wallet(session1["userId"])["coin"], 500)
            state.set_wallet(session1["userId"], {"coin": 1234, "cash": 9})
            session2 = State(path, {"coin": 9999}).login_dev("local-device")
            self.assertEqual(session1["userId"], session2["userId"])
            self.assertEqual(state.wallet(session1["userId"])["coin"], 1234)
            self.assertEqual(state.wallet(session1["userId"])["cash"], 9)
            with self.assertRaises(ValueError):
                state.set_wallet(session1["userId"], {"coin": -1})


